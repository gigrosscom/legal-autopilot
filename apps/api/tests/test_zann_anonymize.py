def run_set() -> tuple[int, int, list[str], list[str]]:
    found = total = 0
    missed: list[str] = []
    lost: list[str] = []
    for text, pii, keep in SAMPLES:
        out, _ = anonymize(text)
        for value in pii:
            total += 1
            # the value is gone: a whole-word occurrence of it no longer appears
            if re.search(rf"(?<![\w]){re.escape(value)}(?![\w])", out):
                missed.append(value)
            else:
                found += 1
        for value in keep:
            if value not in out:
                lost.append(value)
    return found, total, missed, lost


def test_recall_on_labelled_set():
    found, total, missed, lost = run_set()
    recall = found / total
    print(f"anonymisation recall {found}/{total} = {recall:.1%}; missed: {missed}; over-masked: {lost}")
    assert total >= 60
    assert recall >= 0.95, missed
    assert not lost, lost


def test_labels_consistent_within_a_document():
    out, report = anonymize(SAMPLES[0][0])
    # Ахметов Болат …, истец Ахметов, Ахметову, Ахметова Б.С. — one person, one label
    assert out.count("[ФИО1]") >= 3 or out.count("[ФИО3]") >= 3
    first = re.findall(r"\[ФИО\d+\]", out)
    assert len(set(first)) <= 5
    assert "[ИИН1]" in out and "[ТЕЛ1]" in out and "[АДРЕС1]" in out and "[ДЕЛО1]" in out
    assert report.counts["ИИН"] == 1 and report.total >= 8
    assert "850412300123" not in repr(report)  # the report never carries the replaced values


def test_same_value_same_label_and_new_document_restarts():
    out, _ = anonymize("Телефон 87011112233. Повторно: 87011112233. Другой 87014445566.")
    assert out == "Телефон [ТЕЛ1]. Повторно: [ТЕЛ1]. Другой [ТЕЛ2]."
    out2, _ = anonymize("Телефон 87014445566.")
    assert out2 == "Телефон [ТЕЛ1]."


def test_organisation_bin_kept_only_when_clearly_an_organisation():
    out, _ = anonymize("ТОО «Ромашка», БИН 140240012345, против гражданина. Номер 140240012345 в иске.")
    assert "140240012345" in out  # the first one is clearly an organisation
    unsure, _ = anonymize("Взыскать по номеру 140240012345 в пользу взыскателя.")
    assert "140240012345" not in unsure and "[БИН1]" in unsure
    person, _ = anonymize("БИН 850412300123 ТОО «Ромашка»")  # an individual's structure: always masked
    assert "[ИИН1]" in person


def test_record_fields_share_one_numbering():
    rec, _ = anonymize_record({"title": "Иск Ахметова Б.С.", "text": "Истец Ахметов Б.С. просит"})
    assert rec["title"].endswith("[ФИО1]") and "[ФИО1]" in rec["text"]


def test_rules_come_from_the_country_pack():
    import pytest

    assert RULES.labels["person"] == "ФИО" and RULES.labels["id_person"] == "ИИН"
    with pytest.raises(FileNotFoundError):
        load_rules(PACKS, "zz")


def test_plain_legal_text_untouched():
    text = ("Согласно статье 9 Гражданского кодекса Республики Казахстан и пункту 3 нормативного постановления "
            "Верховного Суда Республики Казахстан от 29 июня 2017 года № 5, суд взыскивает неустойку.")
    out, report = anonymize(text)
    assert out == text and report.total == 0
    assert not RULES.label_re.search(out)
